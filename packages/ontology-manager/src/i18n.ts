export type MessageKey = keyof (typeof messages)["en"];

export function ontologyText(locale: string, key: MessageKey, params?: TextParams) {
  const table = locale === "zh-CN" ? messages["zh-CN"] : messages.en;
  return interpolate(table[key] || messages.en[key] || key, params);
}

/**
 * 与工作台共用措辞的词条：沿用原主前端八语种原值。原 vue-i18n 在所缺语种回退部署默认语言，
 * Manager 构建始终是 zh-CN，所以这里回退 zh-CN（开源宿主只传 en，en 词条完整）。
 */
const sharedMessages: Record<string, Record<string, Record<string, string>>> = {
  "zh-CN": sharedZhCN,
  en: sharedEn,
  ja: sharedJa,
  ar: sharedAr,
  "zh-TW": sharedZhTW,
  fr: sharedFr,
  de: sharedDe,
  it: sharedIt,
};

export type SharedKey = {
  [Group in keyof typeof sharedEn]: `${Group}.${keyof (typeof sharedEn)[Group] & string}`;
}[keyof typeof sharedEn];

function sharedLookup(locale: string, key: SharedKey) {
  const [group, name] = key.split(".");
  return sharedMessages[locale]?.[group][name];
}

export function sharedText(locale: string, key: SharedKey, params?: TextParams) {
  return interpolate(sharedLookup(locale, key) ?? sharedLookup("zh-CN", key) ?? key, params);
}

/** Element Plus 语种映射，与原 web useLocale 相同：未列语种回退中文。 */
const elementLocales: Record<string, typeof zhCn> = {
  "zh-CN": zhCn,
  en,
  ja,
  ar,
  "zh-TW": zhTw,
  fr,
  de,
  it,
};

export function elementLocale(locale: string) {
  return elementLocales[locale] || zhCn;
}
